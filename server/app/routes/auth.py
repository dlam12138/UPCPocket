"""Login envelope exchange, browser session and global logout."""

from __future__ import annotations

import hmac
from typing import Literal

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict, Field

from ..crypto import CryptoError, hmac_bytes
from ..errors import ApiError
from ..library.service import LoginRejected, UpstreamFailure
from ..security import client_ip, network_key
from ..sessions import LIBRARY_BRANCHES
from ..upstream.pool import run_blocking
from .deps import (
    audit_context, load_session, require_csrf, require_session, resources,
)


router = APIRouter(prefix="/api")


def _require_station(request: Request) -> None:
    """official 模式不接收任何学校凭据；登录相关端点整体拒绝。"""
    if not resources(request).settings.station_enabled:
        raise ApiError(403, "station_disabled")


class LoginPayload(BaseModel):
    model_config = ConfigDict(extra="forbid")

    kid: str = Field(min_length=1, max_length=64)
    nonce: str = Field(min_length=1, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")
    wrapped: str = Field(min_length=1, max_length=1500)
    iv: str = Field(min_length=1, max_length=64)
    ciphertext: str = Field(min_length=1, max_length=11000)
    branch: Literal["tangdaowan", "east", "qiushi"]
    consent: bool


def hmac_compare(left: str, right: str) -> bool:
    return hmac.compare_digest(left, right)


def set_session_cookie(response: JSONResponse, request: Request, token: str) -> None:
    settings = resources(request).settings
    response.set_cookie(
        settings.cookie_name,
        token,
        max_age=settings.session_absolute_seconds,
        path="/",
        secure=settings.cookie_secure,
        httponly=True,
        samesite="lax",
    )


def clear_session_cookie(response: JSONResponse, request: Request) -> None:
    settings = resources(request).settings
    response.delete_cookie(
        settings.cookie_name,
        path="/",
        secure=settings.cookie_secure,
        httponly=True,
        samesite="lax",
    )


async def _audit_failure(request: Request, branch: str, code: str) -> None:
    res = resources(request)
    audit = audit_context(request)
    try:
        await run_blocking(
            res.database.audit, None, "library_login_failed", audit.ip_hash, audit.ua_hash,
            {"branch": branch, "code": code},
        )
    except Exception:  # noqa: BLE001 - failure audit is best effort
        return


@router.get("/auth/key")
async def auth_key(request: Request):
    _require_station(request)
    # Public key material only. The one-time nonce is generated by the browser
    # and reserved at login, so this unauthenticated GET never writes state.
    return JSONResponse(resources(request).keyring.public_payload())


@router.post("/auth/login")
async def auth_login(request: Request, payload: LoginPayload):
    _require_station(request)
    res = resources(request)
    settings = res.settings
    if not payload.consent:
        raise ApiError(400, "consent_required")
    ip_key = hmac_bytes(
        settings.session_secret, "login-ip", network_key(client_ip(request, settings)),
    ).hex()
    if not await res.limiter.allow(
        "login_ip", ip_key, settings.login_rate_limit, settings.login_rate_window,
    ):
        raise ApiError(429, "rate_limited")
    envelope = {
        "kid": payload.kid, "wrapped": payload.wrapped,
        "iv": payload.iv, "ciphertext": payload.ciphertext,
    }
    try:
        username, password, bound_nonce = res.keyring.decrypt_login(envelope)
    except CryptoError:
        raise ApiError(400, "invalid_request") from None
    # One-time challenge: the browser-generated nonce must match inside and
    # outside the ciphertext and can be reserved only once. A captured envelope
    # therefore cannot be replayed into a session.
    if not hmac_compare(bound_nonce, payload.nonce):
        raise ApiError(400, "invalid_request")
    if not await res.store.reserve_nonce(bound_nonce):
        raise ApiError(400, "invalid_request")
    user_key = hmac_bytes(settings.session_secret, "login-user", username).hex()
    if not await res.limiter.allow(
        "login_user", user_key, settings.login_rate_limit, settings.login_rate_window,
    ):
        raise ApiError(429, "rate_limited")
    existing = await load_session(request)
    try:
        result = await res.login_service.login(
            branch=payload.branch, username=username, password=password,
            existing=existing, audit=audit_context(request),
        )
    except LoginRejected as error:
        await _audit_failure(request, payload.branch, error.code)
        raise ApiError(error.status, error.code) from None
    except UpstreamFailure:
        await _audit_failure(request, payload.branch, "upstream_unavailable")
        raise ApiError(503, "upstream_unavailable") from None
    finally:
        del username, password
    response = JSONResponse({
        "state": "ready",
        "branch": result.branch,
        "revision": result.session.revision,
        "csrf": result.session.csrf,
        "bookingAvailable": settings.booking_enabled,
        "recordsAvailable": result.branch == "tangdaowan",
    })
    set_session_cookie(response, request, result.session.id)
    return response


@router.get("/session")
async def read_session(request: Request):
    res = resources(request)
    session = await load_session(request)
    if session is None:
        return JSONResponse({"state": "anonymous"})
    branches = {
        branch: await res.store.has_library(session.user_id, branch)
        for branch in LIBRARY_BRANCHES
    }
    return JSONResponse({
        "state": "ready",
        "csrf": session.csrf,
        "revision": session.revision,
        "branches": branches,
        "bookingAvailable": res.settings.booking_enabled,
    })


@router.post("/logout")
async def logout(request: Request):
    _require_station(request)
    res = resources(request)
    session = await require_session(request)
    require_csrf(request, session)
    await res.store.drop_libraries(session.user_id)
    await res.store.drop_browser(session.id)
    audit = audit_context(request)
    try:
        await run_blocking(res.database.audit, session.user_id, "web_logout", audit.ip_hash, audit.ua_hash)
    except Exception:  # noqa: BLE001
        pass
    response = JSONResponse({"state": "anonymous"})
    clear_session_cookie(response, request)
    return response
